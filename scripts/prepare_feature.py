"""Stage a self-contained Feature with pinned plugins and personal configuration."""

import argparse
import hashlib
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = ".generated-by-dotfiles"


def prepare(project):
    project = project.resolve()
    if not (project / ".devcontainer" / "devcontainer.json").is_file():
        raise ValueError(f"No .devcontainer/devcontainer.json in {project}")
    target = project / ".devcontainer" / "features" / "devtools"
    if target.is_symlink() or (target.exists() and not (target / MARKER).is_file()):
        raise ValueError(f"Refusing to replace an unowned Feature directory: {target}")
    pins = subprocess.run(["git", "-C", str(ROOT), "submodule", "status", "--recursive"],
                          check=True, capture_output=True, text=True).stdout
    if any(line.startswith(("-", "+", "U")) for line in pins.splitlines()):
        raise ValueError("Initialize the recorded plugins: git submodule update --init --recursive --checkout")
    for line in pins.splitlines():
        path = ROOT / line.split()[1]
        dirty = subprocess.run(["git", "-C", str(path), "status", "--porcelain"],
                               check=True, capture_output=True, text=True).stdout
        if dirty:
            raise ValueError(f"Plugin has uncommitted changes: {path}")
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".devtools-", dir=target.parent) as temporary:
        staged = Path(temporary) / "devtools"
        shutil.copytree(ROOT / "features" / "src" / "devtools", staged)
        source = staged / "source"
        source.mkdir()
        for name in ("pyproject.toml", "requirements-launcher.lock", "requirements-dev.lock",
                     "bashrc", "bash_aliases", "zshrc", "tmux.conf", "install.sh", "infectdots.sh"):
            shutil.copy2(ROOT / name, source)
        for name in ("dotfiles_dev", "nvim", "tmux", "ghostty", "opencode", "vim/bundle",
                     "oh-my-zsh", "zsh", "tests", "docs"):
            shutil.copytree(ROOT / name, source / name,
                            ignore=shutil.ignore_patterns(".git", "__pycache__", "*.pyc",
                                                         "node_modules", ".pytest_cache"))
        (source / "plugin-pins.txt").write_text(pins)
        sources = {
            str(path.relative_to(staged)): {
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "mode": path.stat().st_mode & 0o777,
            }
            for path in sorted(staged.rglob("*")) if path.is_file()
        }
        (staged / "source.json").write_text(json.dumps(sources, indent=2) + "\n")
        (staged / MARKER).write_text("Generated by dotfiles/scripts/prepare_feature.py\n")
        (staged / "install.sh").chmod(0o755)
        if target.exists():
            shutil.rmtree(target)
        staged.rename(target)
    print(f"Prepared {target}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=ROOT,
                        help="Project receiving the local Feature; defaults to dotfiles")
    args = parser.parse_args()
    try:
        prepare(args.project)
    except (ValueError, subprocess.CalledProcessError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
